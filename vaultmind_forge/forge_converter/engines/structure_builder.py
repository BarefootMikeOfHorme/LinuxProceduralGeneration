        structure = {
            "models": [
                "glb",              # Binary GLTF
                "draco"             # Draco compressed
            ],
            "textures": [
                "1024",             # Desktop
                "512",              # Tablet
                "256"               # Mobile
            ],
            "materials": [],        # Three.js JSON
            "basis": [],            # Basis Universal
            "scripts": []           # Three.js loaders
        }

        self._create_directory_structure(web_path, structure)

        conventions = [
            "Model format: GLB with Draco compression",
            "Texture formats: JPG (diffuse), PNG (normal/data)",
            "Max texture size: 1024x1024 (mobile), 2048x2048 (desktop)",
            "Max triangles: 50k per model",
            "Multiple texture sizes for responsive loading",
            "Basis Universal for cross-platform support"
        ]

        self._create_readme(web_path, "Web/Three.js", "Three.js web assets", conventions)

