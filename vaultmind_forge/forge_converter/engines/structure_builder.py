"""
VaultMind Forge - Engine Structure Builder
Adapted from Comprehensive_Ai_Filter/deploy_asset_converter.py

Creates engine-specific directory structures for asset export.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Dict, List, Optional, Any
import json


class EngineStructureBuilder:
    """
    Creates optimized directory structures for game engines.
    Adapted for VaultMind Forge asset pipeline.
    """

    def __init__(
        self,
        base_path: Optional[Path] = None,
        logger: Optional[logging.Logger] = None
    ):
        """
        Initialize structure builder.

        Args:
            base_path: Root assets directory (defaults to LPG/assets)
            logger: Optional logger instance
        """
        if base_path is None:
            # Default to VaultMind Forge assets directory
            base_path = Path(__file__).parents[3] / "assets"

        self.base_path = Path(base_path)
        self.output_path = self.base_path / "output"
        self.logger = logger or self._setup_logger()

        # Ensure output directory exists
        self.output_path.mkdir(parents=True, exist_ok=True)

    def _setup_logger(self) -> logging.Logger:
        """Set up default logger."""
        logger = logging.getLogger("VaultMindForge.EngineStructureBuilder")
        logger.setLevel(logging.INFO)

        if not logger.handlers:
            handler = logging.StreamHandler()
            handler.setLevel(logging.INFO)
            formatter = logging.Formatter(
                '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
            )
            handler.setFormatter(formatter)
            logger.addHandler(handler)

        return logger

    def _create_directory_structure(
        self,
        base: Path,
        structure: Dict[str, Any]
    ) -> None:
        """
        Recursively create directory structure.

        Args:
            base: Base directory
            structure: Dictionary defining structure
        """
        for name, contents in structure.items():
            current_path = base / name

            # Create directory
            try:
                current_path.mkdir(parents=True, exist_ok=True)
                self.logger.debug(f"Created directory: {current_path}")
            except Exception as e:
                self.logger.error(f"Error creating directory {current_path}: {e}")
                continue

            # Handle contents
            if isinstance(contents, list):
                # List of subdirectories
                for item in contents:
                    subdir = current_path / item
                    subdir.mkdir(parents=True, exist_ok=True)
                    self.logger.debug(f"Created subdirectory: {subdir}")

            elif isinstance(contents, dict):
                # Nested structure
                self._create_directory_structure(current_path, contents)

    def _create_readme(
        self,
        path: Path,
        engine_name: str,
        description: str,
        conventions: List[str]
    ) -> None:
        """
        Create README file for engine directory.

        Args:
            path: Directory path
            engine_name: Engine name
            description: Engine description
            conventions: List of naming/format conventions
        """
        readme_path = path / "README.md"

        content = f"""# {engine_name} Assets

## Description
{description}

## Directory Structure
```
{path.name}/
├── models/      # 3D models
├── textures/    # Textures
├── materials/   # Materials
└── ...
```

## Conventions
{chr(10).join(f'- {conv}' for conv in conventions)}

## Generated by VaultMind Forge
This structure was automatically created by forge_converter.
"""

        with open(readme_path, 'w', encoding='utf-8') as f:
            f.write(content)

        self.logger.debug(f"Created README: {readme_path}")

    # ========================================================================
    # Unity Structure
    # ========================================================================

    def create_unity_structure(self, project_name: str = "UnityAssets") -> Path:
        """
        Create Unity-optimized directory structure.

        Args:
            project_name: Project name for this asset pack

        Returns:
            Path to created Unity directory
        """
        unity_path = self.output_path / "unity" / project_name

        structure = {
            "models": [],  # FBX models
            "textures": [
                "diffuse",      # BC7 compressed
                "normal",       # BC5 compressed
                "metallic",     # BC4 compressed
                "roughness",    # BC4 compressed
                "ao"            # BC4 compressed
            ],
            "materials": [],    # .mat files
            "prefabs": [],      # .prefab files
            "animations": [],   # Animation clips
            "shaders": []       # Custom shaders
        }

        self._create_directory_structure(unity_path, structure)

        conventions = [
            "Model format: FBX (2020)",
            "Texture compression: BC7 (diffuse), BC5 (normal), BC4 (single-channel)",
            "Max texture size: 2048x2048",
            "Naming: PascalCase",
            "LOD naming: ModelName_LOD0.fbx, ModelName_LOD1.fbx"
        ]

        self._create_readme(unity_path, "Unity", "Unity game engine assets", conventions)

        # Create .gitkeep files
        for subdir in unity_path.rglob('*'):
            if subdir.is_dir() and not any(subdir.iterdir()):
                (subdir / ".gitkeep").touch()

        self.logger.info(f"[OK] Created Unity structure: {unity_path}")
        return unity_path

    # ========================================================================
    # Unreal Structure
    # ========================================================================

