def test_thread_safety():
    """Test thread-safe concurrent access"""
    manager = ModelManager(max_total_memory_gb=24.0)

    config = ModelConfig(
        name="test-model",
        role=ModelRole.PLANNER,
        model_path="test/model",
        loader_func=create_mock_loader("test-model"),
        max_memory_gb=8.0,
    )

    manager.register_model(config)

    results = []
    errors = []

    def worker():
        try:
            with manager.use_model("test-model") as model:
                time.sleep(0.1)
                results.append(model.name)
        except Exception as e:
            errors.append(e)

    # Create multiple threads
    threads = [threading.Thread(target=worker) for _ in range(5)]

    # Start all threads
    for t in threads:
        t.start()

    # Wait for completion
    for t in threads:
        t.join()

    # Check results
    assert len(errors) == 0
    assert len(results) == 5
    assert all(r == "test-model" for r in results)

    manager.shutdown()


