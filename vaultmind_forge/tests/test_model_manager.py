def test_memory_eviction():
    """Test priority-based memory eviction"""
    manager = ModelManager(max_total_memory_gb=15.0)  # Limited memory

    # Register two models that together exceed limit
    config1 = ModelConfig(
        name="model-1",
        role=ModelRole.PLANNER,
        model_path="test/model1",
        loader_func=create_mock_loader("model-1"),
        max_memory_gb=10.0,
        priority=5,  # Lower priority
    )

    config2 = ModelConfig(
        name="model-2",
        role=ModelRole.DIFFUSION,
        model_path="test/model2",
        loader_func=create_mock_loader("model-2"),
        max_memory_gb=10.0,
        priority=10,  # Higher priority
    )

    manager.register_model(config1)
    manager.register_model(config2)

    # Load model 1
    manager.load_model("model-1")
    assert manager.models["model-1"].state == ModelState.LOADED

    # Load model 2 (should evict model 1)
    with patch.object(manager, '_estimate_model_memory', return_value=10.0):
        manager.load_model("model-2")

    # Model 2 should be loaded
    assert manager.models["model-2"].state == ModelState.LOADED

    manager.shutdown()


