# Mock model for testing (no actual GPU needed)
class MockModel:
    """Mock model for testing"""
    def __init__(self, name: str):
        self.name = name
        self.device = "cpu"

    def generate(self, *args, **kwargs):
        return f"Generated by {self.name}"


def create_mock_loader(model_name: str):
    """Create mock loader function"""
    def loader(config: ModelConfig):
        time.sleep(0.1)  # Simulate load time
        return MockModel(model_name)
    return loader


def test_model_registration():
    """Test model registration"""
    manager = ModelManager(max_total_memory_gb=24.0)

    config = ModelConfig(
        name="test-model",
        role=ModelRole.PLANNER,
        model_path="test/model",
        loader_func=create_mock_loader("test-model"),
        max_memory_gb=8.0,
    )

    manager.register_model(config)

    assert "test-model" in manager.models
    assert manager.models["test-model"].state == ModelState.UNLOADED

    manager.shutdown()


